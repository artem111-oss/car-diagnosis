# Дата последнего пересмотра фактов. Две формы: ISO для schema.org
# (dateModified должен парситься валидаторами), человекочитаемая — в тексте.
UPDATED_ISO = "2026-08-23"
UPDATED = "23 августа 2026"


def _shell(*, path: str, title: str, description: str, h1: str, direct_answer: str = "",
          lede: str = "", body: str, faq: list[tuple[str, str]]) -> str:
    """direct_answer — короткий (40-60 слов) прямой ответ сразу после H1, без
    вступлений: ИИ-поисковики (Perplexity, AI Overviews, ChatGPT search)
    вытаскивают цитаты именно из такого формата, а не из лида или заключения.
    """
    scripts = [{
        "@context": "https://schema.org", "@type": "WebPage",
        "url": f"{DOMAIN}{path}", "name": h1, "description": description,
        "dateModified": UPDATED_ISO, "inLanguage": "ru-RU",
    }]
    if faq:
        scripts.append({
            "@context": "https://schema.org", "@type": "FAQPage",
            "mainEntity": [
                {"@type": "Question", "name": q,
                 "acceptedAnswer": {"@type": "Answer", "text": a}}
                for q, a in faq
            ],
        })
    ld_html = "".join(f'<script type="application/ld+json">{json.dumps(s, ensure_ascii=False)}</script>'
                      for s in scripts)
    faq_html = "".join(f'<div class="faq"><b>{q}</b><span>{a}</span></div>' for q, a in faq)
    answer_html = f'<div class="answer">{direct_answer}</div>' if direct_answer else ""
    lede_html = f'<p class="lede">{lede}</p>' if lede else ""
    return f"""<!doctype html>
<html lang="ru"><head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<link rel="canonical" href="{DOMAIN}{path}">
<link rel="icon" href="/static/favicon.svg" type="image/svg+xml">
<meta name="description" content="{description}">
<title>{title}</title>
{ld_html}
<style>{_STYLE}</style>
</head><body>
<header><div class="wrap" style="border:none;padding:0;margin:0;display:flex;align-items:center;gap:10px">
<a href="/">{BRAND}</a></div></header>
<div class="wrap">
<h1>{h1}</h1>
<p class="updated">Обновлено: {UPDATED}</p>
{answer_html}
{lede_html}
{body}
<h2>Частые вопросы</h2>
{faq_html}
<a class="cta" href="/">Записать звук и проверить бесплатно →</a>
<footer>{BRAND} — предварительная подсказка по звуку, не заменяет осмотр специалиста.</footer>
</div></body></html>"""


def _causes_page(*, path, title, description, h1, direct_answer="", lede="", causes, faq):
    body = "".join(
        f'<div class="cause"><b>{name}</b><span class="badge {level}">{level_ru}</span>'
        f'<p style="margin:6px 0 0">{desc}</p></div>'
        for name, level, level_ru, desc in causes
    )
    return _shell(path=path, title=title, description=description, h1=h1,
                 direct_answer=direct_answer, lede=lede, body=body, faq=faq)


