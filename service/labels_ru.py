def part_ru(part: str) -> PartInfo:
    """Русская карточка узла. Неизвестные метки не роняют ответ."""
    return PARTS.get(part) or PartInfo(part, "accessory", LOW, "")


def region_ru(zone: str) -> str:
    return REGIONS.get(zone, zone)


def zones_agree(zone: str, part: str) -> bool:
    """Принадлежит ли деталь названной зоне.

    Головы region и cause обучались раздельно и согласованности между ними никто
    не гарантировал: на demo.wav из репозитория модель одновременно выдаёт зону
    «подвеска» и деталь «выхлоп». Показывать такое владельцу нельзя.
    """
    info = PARTS.get(part)
    return info is not None and info.zone == zone
